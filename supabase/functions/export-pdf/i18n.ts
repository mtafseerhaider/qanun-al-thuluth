export function t(
  strings: Strings | (typeof STRINGS)['ur'],
  key: keyof Strings,
  vars: Record<string, string | number> = {},
): string {
  const raw = strings[key];
  if (typeof raw !== 'string') throw new Error(`not a string key: ${String(key)}`);
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}
