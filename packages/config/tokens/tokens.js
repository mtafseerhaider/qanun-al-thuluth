/** "#1F6F5C" -> "31 111 92" for rgb(var(--x) / <alpha-value>) usage. */
export function hexToRgbTriplet(hex) {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
}

/** CSS variable map for NativeWind vars(): { '--color-surface': '251 248 242', ... }. */
export function cssVarsFor(theme) {
  const out = {};
  for (const name of colorTokenNames) out[`--color-${name}`] = hexToRgbTriplet(colors[theme][name]);
  return out;
}
